def age_hours(topic_index: int, message_index: int, count: int) -> int:
    if topic_index == 0 and message_index == count - 1:
        return 3
    if topic_index == 1 and message_index == count - 1:
        return 18
    if topic_index == 2 and message_index == count - 1:
        return 6
    if topic_index == 3 and message_index == count - 1:
        return 12
    return 36 + topic_index * 30 + (count - 1 - message_index) * 8


def build(topic_index: int, slug: str, subject: str, lines: list[str]) -> None:
    ids: list[str] = []
    people = [
        ("И. Петров", "petrov@partner.example"),
        ("А. Сидорова", "sidorova@company.example"),
        ("Вы", "you@company.example"),
        ("Бухгалтерия", "accounts@company.example"),
    ]
    for index, line in enumerate(lines):
        if topic_index == 0 and index == len(lines) - 1:
            name, mailbox = ("И. Петров", "petrov@partner.example")
        else:
            name, mailbox = people[index % len(people)]
        message_id = f"<t{topic_index}-{slug}-{index}@fixture.local>"
        email = EmailMessage()
        email["From"] = f"{name} <{mailbox}>"
        email["To"] = "Вы <you@company.example>"
        if index == 2:
            email["Cc"] = "А. Сидорова <sidorova@company.example>"
        email["Subject"] = subject if index == 0 else f"Re: {subject}"
        email["Message-ID"] = message_id
        email["Date"] = formatdate(localtime=False)
        email["X-Fixture-Age-Hours"] = str(age_hours(topic_index, index, len(lines)))
        if ids:
            email["In-Reply-To"] = ids[-1]
            email["References"] = " ".join(ids)
        if topic_index == 4 and index == 5:
            email.set_content("<p>Цена предложения — 4 800 000 рублей. Файл спецификации во вложении нет, это HTML-версия.</p>", subtype="html", charset="utf-8")
        else:
            email.set_content(line, charset="utf-8")
            if topic_index == 0 and index == 5:
                email.add_attachment(b"act", maintype="application", subtype="octet-stream", filename="final-act.pdf")
        ids.append(message_id)
        path = OUT / f"{topic_index:02d}-{index:02d}-{slug}.eml"
        path.write_bytes(email.as_bytes())


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.eml"):
        old.unlink()
    for topic_index, (slug, subject, lines) in enumerate(TOPICS):
        build(topic_index, slug, subject, lines)
    print(len(list(OUT.glob('*.eml'))))


if __name__ == "__main__":
    main()
